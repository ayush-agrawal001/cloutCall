// Regenerates lib/abi.ts from the Foundry build output. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "..", "contracts", "out");
const read = (name) => JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8")).abi;

const src = `// Generated by scripts/gen-abi.mjs — do not edit by hand.
export const marketAbi = ${JSON.stringify(read("CloutMarket"), null, 2)} as const;

export const pointsAbi = ${JSON.stringify(read("CloutPoints"), null, 2)} as const;
`;
writeFileSync(join(root, "lib", "abi.ts"), src);
console.log("wrote lib/abi.ts");
